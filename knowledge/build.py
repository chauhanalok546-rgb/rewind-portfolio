#!/usr/bin/env python3
"""Builds everything from qa_data.py so the readable list, the AI's instructions and the offline fallback answers can never disagree.
   python3 knowledge/build.py   ->  knowledge/judge-qa.md, api/_qa.ts, public/audio/answers/answers.json (adds the qa_* entries)"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from qa_data import QA
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENES = {"scene1": "childhood and chess", "scene2": "Java, Class 10, mountaineering", "scene3": "Dehradun, basketball, NDA, SSB", "scene4": "NST, hackathons, projects", "scene5": "goals, Wispr Flow", "scene6": "contact"}

# ---- 1. the readable list
NEED = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "needs.md")).read() if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "needs.md")) else ""
md = ["# Judge Q&A: what the avatar knows", "", "Every answer below is built only from facts you gave (or can be seen in your photos). **R** = from your facts; **C** = please confirm (built from your photos or a reasonable reading). The AI also gets this whole list as its approved answers, so it stays consistent even when a judge phrases a question differently, and these answers are the fallback if the live AI is ever offline.", ""]
group = None
for (i, g, qs, a, gest, mood, jump, st) in QA:
    if g != group: md += ["", f"## {g}", ""]; group = g
    md += [f"**Q: {qs[0]}**" + (f"  _(also: {'; '.join(qs[1:])})_" if len(qs) > 1 else ""), f"A: {a}" + (f"  → jumps to the story: {SCENES.get(jump, jump)}" if jump else "") + f"  `[{st}]`", ""]
md += ["", NEED]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "judge-qa.md"), "w").write("\n".join(md))

# ---- 2. the AI's approved answers (included in its system prompt)
lines = ["APPROVED ANSWERS. When a visitor asks one of these questions, or something very close, answer with this content in your own natural spoken words, and never add facts that are not here or in the facts above. Use the jump scene when it is given.", ""]
for (i, g, qs, a, gest, mood, jump, st) in QA:
    lines.append("Q: " + " / ".join(qs[:3]) + "\nA: " + a + (f"\n(jumpTo {jump})" if jump else ""))
    lines.append("")
qa_text = "\n".join(lines).replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
open(os.path.join(ROOT, "api", "_qa.ts"), "w").write("// Generated by knowledge/build.py from knowledge/qa_data.py. Do not edit by hand.\nexport const QA_TEXT = `" + qa_text + "`\n")

# ---- 3. offline fallback answers (spoken with the browser voice; no recorded audio for these)
p = os.path.join(ROOT, "public/audio/answers/answers.json"); d = json.load(open(p))
d["answers"] = [a for a in d["answers"] if not a["id"].startswith("qa_")]
norm = lambda s: re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]+", " ", s.lower().replace("'", " ").replace("’", " "))).strip()
for (i, g, qs, a, gest, mood, jump, st) in QA:
    keys = sorted({norm(q) for q in qs if len(norm(q).split()) >= 2})
    d["answers"].append({"id": "qa_" + i, "q": qs[0], "keys": keys, "say": a, "gesture": {"talk": "talk1", "point": "point", "shrug": "present"}.get(gest, "talk1"), "mood": mood, "jumpTo": jump})
json.dump(d, open(p, "w"), indent=1, ensure_ascii=False)
print(len(QA), "approved answers;", sum(len(a["keys"]) for a in d["answers"]), "match phrases in total")
